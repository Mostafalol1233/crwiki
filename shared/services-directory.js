export function normalizeServiceListing(row = {}) {
  const contacts = { ...EMPTY_CONTACTS, ...(row.contacts || {}) };
  if (!contacts.funpay && row.profile_url) contacts.funpay = row.profile_url;
  const profileUrl = row.profile_url || contacts.funpay || '';
  const gallery = Array.isArray(row.gallery) ? row.gallery.filter(Boolean) : [];
  return {
    id: row.id ? String(row.id) : undefined,
    seller: String(row.seller_name || row.seller || ''),
    sellerSlug: String(row.seller_slug || ''),
    profileUrl,
    service: String(row.service_name || row.service || ''),
    serviceAr: String(row.service_name_ar || row.service_ar || ''),
    price: String(row.price_snapshot || row.price || ''),
    priceAr: String(row.price_snapshot_ar || row.price_ar || ''),
    age: String(row.observed_at_label || row.age || ''),
    ageAr: String(row.observed_at_label_ar || row.age_ar || ''),
    confidence: row.confidence === 'higher' || row.confidence === 'limited' || row.confidence === 'unverified' ? row.confidence : 'unverified',
    note: String(row.note || ''),
    noteAr: String(row.note_ar || ''),
    mediaUrl: String(row.media_url || ''),
    gallery,
    mediaSource: String(row.media_source || ''),
    mediaSourceAr: String(row.media_source_ar || ''),
    contacts,
    published: row.published !== false,
    featured: Boolean(row.featured),
    sortOrder: Number(row.sort_order || 9999),
  };
}

export function getDefaultServiceListings() {
  return DEFAULT_SERVICE_LISTINGS.map((item) => normalizeServiceListing(item));
}

export function getListingContactLinks(listing) {
  const contacts = listing?.contacts || {};
  return SERVICE_CONTACT_FIELDS
    .map((field) => ({ key: field.key, label: field.label, value: String(contacts[field.key] || '').trim() }))
    .filter((item) => item.value);
}
